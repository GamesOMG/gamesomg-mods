        public const string English = "english";

        // the game's current language id ("french"); Plugin points it at the game, the tests at whatever they check
        public static Func<string> Language = () => English;

        public static string Current
        {
            get { try { return Language?.Invoke() ?? English; } catch (Exception) { return English; } }
        }

        public static string T(string id, params object[] args) => In(Current, id, args);

        public static string In(string language, string id, params object[] args)
        {
            string line = null;
            if (language != null && Tables.TryGetValue(language, out var table)) table.TryGetValue(id, out line);
            if (line == null && !Tables[English].TryGetValue(id, out line)) return id;
            return args == null || args.Length == 0 ? line : string.Format(CultureInfo.InvariantCulture, line, args);
        }

        public static string N(string id, int count, params object[] args)
        {
            var all = new object[(args?.Length ?? 0) + 1];
            all[0] = count;
            if (args != null) Array.Copy(args, 0, all, 1, args.Length);
            return T(id + (count == 1 ? ".1" : ".n"), all);
        }

        public static bool Has(string id) => id != null && (Tables[English].ContainsKey(id) || Tables[English].ContainsKey(id + ".1"));

        public static IEnumerable<string> Ids => Tables[English].Keys;

        // the languages with a table (the game's own identifiers), English first
        public static IEnumerable<string> Languages => Tables.Keys;

        public static bool Translated(string language) => language != null && Tables.ContainsKey(language);

        // "1.25" / "1,25": at most two decimals, no trailing zeros, the language's decimal mark
        public static string Number(double value)
        {
            string s = Math.Round(value, 2).ToString("0.##", CultureInfo.InvariantCulture);
            return s.Replace(".", T("num.decimal"));
        }

