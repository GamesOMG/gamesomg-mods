// GamesOMG Item Spawner: every line the mod shows a player, in every language The Planet Crafter itself ships (its own list,
// GameConfig.TranslatedLangages, build 26411416: english french spanish portuguese german schinese tchinese japanese korean
// polish russian turk italian). Code asks by id: L.T("result.added", n, name). {0}, {1}… are filled in order; L.N picks
// "<id>.1" or "<id>.n" by the count ({0}).
//   · the language is the game's own current one (Plugin sets L.Language to read it), so the panel follows the game's
//     Options; a language the table doesn't have, or a line missing from one, falls back to English
//   · item names, item descriptions, building names and the game's labels ("Oxygen multiplier", "Free build") are never
//     here: they come from the game, in the player's language. These are GamesOMG's own words, translated by us
//     (2026-11-21); the README says which is which
//   · counts are said as "{0} × {1}" so no language has to agree a plural or a case with a number or an item name
// tests/strings_test.py fails when code asks for an id that is not here, an id here is never used, a language lacks an id,
// or a translation's blanks ({0}, {1}…) differ from the English line's. Log lines stay English in the code.
