        public static string T(string id, params object[] args)
        {
            if (!En.TryGetValue(id, out var line)) return id;
            return args == null || args.Length == 0 ? line : string.Format(CultureInfo.InvariantCulture, line, args);
        }

        public static string N(string id, int count, params object[] args)
        {
            var all = new object[(args?.Length ?? 0) + 1];
            all[0] = count;
            if (args != null) Array.Copy(args, 0, all, 1, args.Length);
            return T(id + (count == 1 ? ".1" : ".n"), all);
        }

        public static bool Has(string id) => id != null && (En.ContainsKey(id) || En.ContainsKey(id + ".1"));

        // the id of a line with no blanks, for Diagnostics (it keeps ids, never the text); null when the text is not one
        public static string IdOf(string text)
        {
            if (string.IsNullOrEmpty(text)) return null;
            foreach (var kv in En) if (kv.Value == text) return kv.Key;
            return null;
        }

        public static IEnumerable<string> Ids => En.Keys;

