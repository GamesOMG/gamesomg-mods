// GamesOMG Teleport 0.3.0: every line the mod shows a player, in one table, ready for translation (ChatGPT's review
// 2026-11-19, "externalise strings"). Code asks for a line by id: L.T("land.noRoom"), L.N("import.added", n, …) picks
// "<id>.1" or "<id>.n" by the count. {0}, {1}… are filled in order (L.N: {0} is the count). Labels may grow in another
// language; the panel wraps them. Log lines (LogOutput.log) stay in English in the code: they are for bug reports.
// tests/strings_test.py fails when code asks for an id that is not here, or an id here is never used.
using System;
using System.Collections.Generic;
