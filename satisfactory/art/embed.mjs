// GamesOMG Teleport for Satisfactory: the gear-G mark and the icon sheet, as bytes in the DLL (the Planet Crafter mod embeds
// the same two PNGs as resources). A Slate brush is made from them at runtime (GOMGTheme.cpp), so the mod needs no .pak.
//   node satisfactory/art/embed.mjs   → GamesOMGTeleport/Source/GamesOMGTeleport/Private/GOMGArt.inl
// mark.png and icons.png are the Planet Crafter mod's (planet-crafter/data), byte for byte. icons.png is one row of 64 px
// squares, white, tinted when drawn, in the order of EGOMGIcon (GOMGTheme.h), which is Planet Crafter's Icon enum.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, '..', 'GamesOMGTeleport', 'Source', 'GamesOMGTeleport', 'Private', 'GOMGArt.inl');

function bytes(name) {
  const b = readFileSync(join(here, name));
  const lines = [];
  for (let i = 0; i < b.length; i += 24) lines.push('\t' + [...b.subarray(i, i + 24)].map((v) => '0x' + v.toString(16).padStart(2, '0')).join(', ') + ',');
  return { b, text: lines.join('\n') };
}

const mark = bytes('mark.png');
const icons = bytes('icons.png');
writeFileSync(out, `// GENERATED by satisfactory/art/embed.mjs from satisfactory/art/*.png. Do not edit by hand.
// mark.png ${mark.b.length} bytes, icons.png ${icons.b.length} bytes.
static const uint8 GOMG_MARK_PNG[] = {
${mark.text}
};
static const uint8 GOMG_ICONS_PNG[] = {
${icons.text}
};
`);
console.log('wrote', out);
